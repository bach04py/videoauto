TEXT_SCRIPT = "Mở đầu phòng tập\nTEXT: ĐỐT MỠ ĐÓN TẾT\nKết bằng logo\n"


def no_vi(cat: dict) -> dict:
    cat = json.loads(json.dumps(cat))
    for it in cat["items"]:
        for k in [k for k in it if k.startswith("vi_")]:
            del it[k]
    return cat


def cfg_in(tmp_path, cat: dict, extra: str = "") -> object:
    (tmp_path / "catalogue.json").write_text(json.dumps(cat), encoding="utf-8")
    (tmp_path / "config.yaml").write_text("catalogue: catalogue.json\nopenchatcut:\n  repo: nowhere\n" + extra,
                                          encoding="utf-8")
    return load_project_config(tmp_path / "config.yaml")


