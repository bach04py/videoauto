@pytest.fixture
def fake_occ_repo(tmp_path):
    repo = tmp_path / "OpenChatCut"
    (repo / "scripts").mkdir(parents=True)
    (repo / "node_modules" / "tsx").mkdir(parents=True)
    (repo / "assets" / "templates").mkdir(parents=True)
    (repo / "assets" / "templates" / "a.json").write_text("[]", encoding="utf-8")
    (repo / "package.json").write_text('{"version": "1.0.0"}', encoding="utf-8")
    return repo


def fake_dump(monkeypatch, oc, seen: dict, code: int = 0):
    def run(cmd, cwd, **kw):
        seen["cmd"], seen["cwd"] = cmd, cwd
        seen["copied"] = (Path(cwd) / cmd[3]).is_file()
        seen["stack"] = (Path(cmd[5]) / "vi-stack-review.json").read_bytes()
        if code == 0:
            cat = json.loads(json.dumps(CATALOGUE))
            cat["counts"] = {"effect": 1, "lut": 1, "transition": 1, "template": 3}
            Path(cmd[4]).write_text(json.dumps(cat), encoding="utf-8")
        return subprocess.CompletedProcess(cmd, code, "", "" if code == 0 else "Error: readFile ENOENT")
    monkeypatch.setattr(oc.subprocess, "run", run)


def test_generate_copies_runs_cleans_and_stamps(tmp_path, fake_occ_repo, real_catalogue, monkeypatch):
    oc, seen = real_catalogue, {}
    fake_dump(monkeypatch, oc, seen)
    monkeypatch.setattr(oc, "git_head", lambda repo: "abc1234")
    out = tmp_path / "catalogue.json"
    said = []
    assert oc.ensure(out, fake_occ_repo, "node", say=said.append) is True
    assert seen["copied"] and seen["cwd"] == fake_occ_repo
    assert seen["cmd"][:3] == ["node", "--import", "tsx"]
    assert seen["stack"] == (oc.BUNDLE / "vi-stack-review.json").read_bytes()      # upstream OpenChatCut
    assert not (fake_occ_repo / "scripts" / oc.COPIED_NAME).exists()
    stamp = json.loads(out.read_text(encoding="utf-8"))["videoauto"]
    assert stamp["fingerprint"] == oc.fingerprint(fake_occ_repo) and stamp["openchatcut_git"] == "abc1234"
    assert "chưa có catalogue.json" in said[0] and "vi_ok" in said[-1]
    assert oc.ensure(out, fake_occ_repo, "node", say=said.append) is False          # current: untouched

    # another OpenChatCut version (a template changed): regenerated, not used as is
    (fake_occ_repo / "assets" / "templates" / "a.json").write_text('[{"id": "new"}]', encoding="utf-8")
    assert "bản OpenChatCut khác" in oc.why_stale(out, fake_occ_repo)
    assert oc.ensure(out, fake_occ_repo, "node", say=said.append) is True


